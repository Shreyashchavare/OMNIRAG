    def test_generate_python_assertions_for_java(self):
        now = int(time.time())

        valid_token = create_python_assertion()
        expired_token = create_python_assertion(iat=now - 7200, exp=now - 3600)
        future_token = create_python_assertion(iat=now + 3600, exp=now + 7200)
        wrong_issuer_token = create_python_assertion(iss="rogue-service")
        invalid_uuid_token = create_python_assertion(sub="not-a-valid-uuid")
        missing_rid_token = create_python_assertion(rid="")

        # Tampered payload
        parts = valid_token.split(".")
        tampered_dict = {
            "sub": "8ba91f24-1234-4562-b3fc-2c963f66afa7",
            "roles": TEST_ROLES,
            "iss": TEST_ISSUER,
            "iat": now,
            "exp": now + 60,
            "rid": TEST_REQUEST_ID
        }
        tampered_b64 = base64.urlsafe_b64encode(json.dumps(tampered_dict).encode("utf-8")).decode("utf-8").rstrip("=")
        tampered_payload_token = f"{tampered_b64}.{parts[1]}"

        # Tampered signature
        tampered_sig_token = f"{parts[0]}.{parts[1][:-2]}00"

        # Invalid sig length
        invalid_sig_length_token = f"{parts[0]}.{parts[1][:40]}"

        # Mismatched rid token
        mismatched_rid_token = create_python_assertion(rid="req-original-from-token")

        python_tokens = {
            "test_secret": TEST_SECRET,
            "expected_sub": TEST_USER_ID,
            "expected_roles": TEST_ROLES,
            "expected_rid": TEST_REQUEST_ID,
            "expected_iss": TEST_ISSUER,
            "valid_token": valid_token,
            "expired_token": expired_token,
            "future_token": future_token,
            "wrong_issuer_token": wrong_issuer_token,
            "invalid_uuid_token": invalid_uuid_token,
            "missing_rid_token": missing_rid_token,
            "tampered_payload_token": tampered_payload_token,
            "tampered_signature_token": tampered_sig_token,
            "invalid_sig_length_token": invalid_sig_length_token,
            "mismatched_rid_token": mismatched_rid_token
        }

        output_file = fixtures_dir / "python_to_java_assertions.json"
        with open(output_file, "w", encoding="utf-8") as f:
            json.dump(python_tokens, f, indent=2)

        self.assertTrue(output_file.exists())


