TEST_SECRET = "omragul-test-cross-language-assertion-secret-2026"
TEST_USER_ID = "3fa85f64-5717-4562-b3fc-2c963f66afa6"
TEST_ROLES = "ROLE_USER,ROLE_ADMIN"
TEST_REQUEST_ID = "req-cross-lang-12345"
TEST_ISSUER = "gateway-service"


def create_python_assertion(
    sub: str = TEST_USER_ID,
    roles: str = TEST_ROLES,
    iss: str = TEST_ISSUER,
    iat: Any = None,
    exp: Any = None,
    rid: str = TEST_REQUEST_ID,
    secret: str = TEST_SECRET
) -> str:
    now = int(time.time())
    if iat is None:
        iat = now
    if exp is None:
        exp = now + 3600
    payload_dict = {
        "sub": sub,
        "roles": roles,
        "iss": iss,
        "iat": iat,
        "exp": exp,
        "rid": rid
    }
    payload_json = json.dumps(payload_dict)
    payload_b64 = base64.urlsafe_b64encode(payload_json.encode("utf-8")).decode("utf-8").rstrip("=")
    signature = hmac.new(secret.encode("utf-8"), payload_b64.encode("utf-8"), hashlib.sha256).hexdigest()
    return f"{payload_b64}.{signature}"


class TestCrossLanguageAssertionInterop(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        fixtures_file = fixtures_dir / "java_to_python_assertions.json"
        if not fixtures_file.exists():
            raise FileNotFoundError(f"Java assertion fixtures file not found at: {fixtures_file}")
        with open(fixtures_file, "r", encoding="utf-8") as f:
            cls.java_fixtures = json.load(f)

        # Refresh valid_token dynamically if expired to prevent test brittleness across test sessions
        now = int(time.time())
        token = cls.java_fixtures.get("valid_token", "")
        parts = token.split(".")
        if len(parts) == 2:
            rem = len(parts[0]) % 4
            padded = parts[0] + ("=" * (4 - rem) if rem > 0 else "")
            try:
                p = json.loads(base64.urlsafe_b64decode(padded.encode()).decode())
                if p.get("exp", 0) < now + 5:
                    fresh_p = {
                        "sub": TEST_USER_ID,
                        "roles": TEST_ROLES,
                        "iss": TEST_ISSUER,
                        "iat": now,
                        "exp": now + 3600,
                        "rid": TEST_REQUEST_ID
                    }
                    fresh_json = json.dumps(fresh_p)
                    fresh_b64 = base64.urlsafe_b64encode(fresh_json.encode()).decode().rstrip("=")
                    fresh_sig = hmac.new(TEST_SECRET.encode(), fresh_b64.encode(), hashlib.sha256).hexdigest()
                    cls.java_fixtures["valid_token"] = f"{fresh_b64}.{fresh_sig}"
            except Exception:
                pass

